// DEMO_MODE: serve canned responses so the live demo survives bad Wi-Fi or API rate limits.

import type { Axis, Idea, Provocation, SessionState } from "./contract";
import demoData from "./demo-data.json";

const DEFAULT_CANNED_REPLY =
  "This is a canned DEMO_MODE reply. Replace it in src/lib/demo.ts with a realistic answer from your demo script.";
const STREAM_CHUNK_CHARS = 12;
const STREAM_CHUNK_DELAY_MS = 20;

export function isDemoMode(): boolean {
  return process.env.DEMO_MODE === "true";
}

/** Canned AI replies keyed by feature id. Add one per AI feature in docs/SPEC.md §4. */
export const CANNED_AI_REPLIES: Readonly<Record<string, string>> = {
  default: DEFAULT_CANNED_REPLY,
};

export function cannedReply(feature = "default"): string {
  return CANNED_AI_REPLIES[feature] ?? DEFAULT_CANNED_REPLY;
}

/** Streams text in small chunks so canned replies look like a live model response. */
export function streamText(text: string): ReadableStream<Uint8Array> {
  const encoder = new TextEncoder();
  let offset = 0;
  return new ReadableStream<Uint8Array>({
    async pull(controller) {
      if (offset >= text.length) {
        controller.close();
        return;
      }
      controller.enqueue(encoder.encode(text.slice(offset, offset + STREAM_CHUNK_CHARS)));
      offset += STREAM_CHUNK_CHARS;
      await new Promise((resolve) => setTimeout(resolve, STREAM_CHUNK_DELAY_MS));
    },
  });
}

// ---------- Blind Spot seeded demo session ----------
// Generated by scripts/seed.ts (cached embeddings, no network needed).

export const DEMO_SESSION_ID = "00000000-0000-4000-8000-0000000000d3";
const DEMO_START_MS = Date.UTC(2026, 9, 17, 21, 0);
const DEMO_IDEA_GAP_MS = 2 * 60_000;
const PROVOCATION_DELAY_MS = 30_000;
/** Mean pairwise cosine distance of short-phrase embeddings runs ~0.7; this maps it to ~0.4. */
const SPREAD_CALIBRATION = 1.75;
const END_SCORE_THRESHOLD = 0.3;
const END_MIN_IDEAS = 2;
/** Must match SCORE_SCALE in src/lib/engine/score.ts: raw cos(e,poleB)-cos(e,poleA) of ~0.08 maps to a full ±1. */
const SCORE_SCALE = 0.08;

const isoAt = (offsetMs: number): string => new Date(DEMO_START_MS + offsetMs).toISOString();
const clamp01 = (v: number): number => Math.max(0, Math.min(1, v));
const axisId = (i: number): string => `demo-ax-${i + 1}`;
const ideaId = (j: number): string => `demo-i-${j + 1}`;

export type DemoEmbeddings = {
  ideas: ReadonlyArray<{ id: string; text: string; embedding: readonly number[] }>;
  axes: ReadonlyArray<{
    id: string;
    poleA: string;
    poleB: string;
    embeddingA: readonly number[];
    embeddingB: readonly number[];
  }>;
};

/** Cached embeddings for the seeded ideas and axis poles. */
export function DEMO_EMBEDDINGS(): DemoEmbeddings {
  return {
    ideas: demoData.ideas.map((idea, j) => ({ id: ideaId(j), text: idea.text, embedding: idea.embedding })),
    axes: demoData.axes.map((ax, i) => ({ id: axisId(i), ...ax })),
  };
}

/** Axes for the "propose axes" canned path. */
export function getDemoAxes(): Axis[] {
  return demoData.axes.map((ax, i) => ({
    id: axisId(i),
    poleA: ax.poleA,
    poleB: ax.poleB,
    userEdited: false,
    position: i,
  }));
}

/** Absolute axis score (no per-session normalization), so a one-sided brainstorm shows up as a real gap. */
function axisScore(embedding: readonly number[], ax: { embeddingA: readonly number[]; embeddingB: readonly number[] }): number {
  const raw = cosineDistance(embedding, ax.embeddingA) - cosineDistance(embedding, ax.embeddingB);
  return Math.max(-1, Math.min(1, raw / SCORE_SCALE));
}

export function getDemoIdeas(): Idea[] {
  return demoData.ideas.map((idea, j) => {
    const scores = demoData.axes.map((ax) => axisScore(idea.embedding, ax));
    return {
      id: ideaId(j),
      text: idea.text,
      source: "typed",
      speaker: idea.speaker,
      axisScores: Object.fromEntries(scores.map((s, i) => [axisId(i), s])),
      pca: { x: scores[0], y: scores[1] },
      createdAt: isoAt(j * DEMO_IDEA_GAP_MS),
    };
  });
}

function cosineDistance(a: readonly number[], b: readonly number[]): number {
  let dot = 0;
  let na = 0;
  let nb = 0;
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i];
    na += a[i] * a[i];
    nb += b[i] * b[i];
  }
  return 1 - dot / Math.sqrt(na * nb);
}

function meanPairwiseDistance(vectors: ReadonlyArray<readonly number[]>): number {
  let total = 0;
  let pairs = 0;
  for (let i = 0; i < vectors.length; i++) {
    for (let j = i + 1; j < vectors.length; j++) {
      total += cosineDistance(vectors[i], vectors[j]);
      pairs++;
    }
  }
  return pairs === 0 ? 0 : total / pairs;
}

function computeCoverage(ideas: Idea[], axes: Axis[]): number {
  let covered = 0;
  for (const ax of axes) {
    const scores = ideas.map((i) => i.axisScores[ax.id] ?? 0);
    if (scores.filter((s) => s <= -END_SCORE_THRESHOLD).length >= END_MIN_IDEAS) covered++;
    if (scores.filter((s) => s >= END_SCORE_THRESHOLD).length >= END_MIN_IDEAS) covered++;
  }
  return covered / (axes.length * 2);
}

/** Canned provocations: questions only, never ideas. Oldest first. */
export function getDemoProvocations(): Provocation[] {
  const ideas = getDemoIdeas();
  return [
    {
      id: "demo-p-1",
      type: "fixation",
      text: "Four of these ideas add a layer of guidance on top of the same first screen. What are they all assuming about where a new user's confusion begins?",
      why: {
        pattern: "fixation",
        ideaIds: [ideas[1].id, ideas[2].id, ideas[5].id, ideas[7].id],
        explanation: "Several ideas are close neighbours: they all explain or decorate the existing product screens.",
      },
      status: "dismissed",
      createdAt: isoAt(5 * DEMO_IDEA_GAP_MS + PROVOCATION_DELAY_MS),
    },
    {
      id: "demo-p-2",
      type: "gap",
      text: "All 8 ideas sit on the incremental end. What would a radical version of onboarding even have to change?",
      why: {
        pattern: "gap",
        ideaIds: ideas.map((i) => i.id),
        axisId: axisId(0),
        explanation: "Every idea scores toward “incremental” on the incremental ↔ radical lens; the radical end is empty.",
      },
      status: "shown",
      createdAt: isoAt(8 * DEMO_IDEA_GAP_MS + PROVOCATION_DELAY_MS),
    },
  ];
}

/** Full seeded SessionState for DEMO_MODE (contract shape). */
export function getDemoSessionState(): SessionState {
  const axes = getDemoAxes();
  const ideas = getDemoIdeas();
  const spread = clamp01(meanPairwiseDistance(demoData.ideas.map((i) => i.embedding)) / SPREAD_CALIBRATION);
  const coverage = computeCoverage(ideas, axes);
  return {
    session: {
      id: DEMO_SESSION_ID,
      prompt: demoData.prompt,
      teamName: "Demo Team",
      createdAt: isoAt(0),
    },
    axes,
    ideas,
    provocations: getDemoProvocations(),
    diversity: Math.round((0.6 * spread + 0.4 * coverage) * 100),
    diversityBreakdown: { spread, coverage },
  };
}
